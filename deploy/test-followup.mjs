let snapshot = await w.eval('api')('/api/workbench');
assert.equal(snapshot.events[0].actor, '运营甲');
assert.equal(snapshot.events[0].actor_id, 'user-1');
w.setOpsFollowupContext({...context,user:{id:'user-2',name:'物流乙'}});
